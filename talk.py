def build_vote_clause(yesterday_votes, exiled_yesterday, my_name, rng):
    """
    前日の追放投票についての文。
    投票は一斉に指名する公開情報なので、どの役職が言及しても安全。
    「追放の結果」「票が集まった人」「棄権した人」の中から1つ選ぶ。
    """
    if not yesterday_votes:
        return None

    choices = []

    if exiled_yesterday is not None:
        choices.append(rng.choice(VOTE_EXILED_LINES).format(p=exiled_yesterday))
    else:
        choices.append(rng.choice(VOTE_NO_EXILE_LINES))

    counts = {}
    for target in yesterday_votes.values():
        if target is not None:
            counts[target] = counts.get(target, 0) + 1
    if counts:
        top_n = max(counts.values())
        top = sorted(p for p, n in counts.items() if n == top_n)
        choices.append(rng.choice(VOTE_FOCUS_LINES).format(p=rng.choice(top), n=top_n))

    # 棄権者への言及。自分自身は「あいつ棄権してた」と名指ししない
    abstained = sorted(v for v, t in yesterday_votes.items() if t is None and v != my_name)
    if abstained and len(abstained) <= 3:
        choices.append(rng.choice(VOTE_ABSTAIN_LINES).format(absent="・".join(abstained)))

    return rng.choice(choices)


