def suspicion_score(worlds, player):
    return engine.role_ratio(worlds, player, "カロン") + engine.role_ratio(worlds, player, "セイレーン")


def is_undetermined(worlds, player):
    s = suspicion_score(worlds, player)
    return 0.0 < s < 1.0


def _pick(pool, rng):
    """空文字列も混ざったプールから1つ選ぶ（空なら None 扱いにする）"""
    choice = rng.choice(pool)
    return choice if choice else None


def _pick_fresh(pool, spoken, rng, allow_none=False):
    """
    プールから1つ選ぶ。ただし、★その日すでに誰かが使った文は避ける。

    ★なぜ「話題」ではなく「文そのもの」で重複を見るのか
      朝のひとり言には spoken_topics（話題ごと1人だけが話す）という仕組みが
      あるが、あれは「前日の操舵室の顔ぶれ」のような公開情報の要約に対する
      もので、何人も復唱する価値が無いから成り立っている。
      これに対して夜の発言は、4つの部品すべてが個人の発言（自分がどの部屋に
      いたか／図書室の報告を信じるか／誰を疑うか／誰に投票するか）なので、
      話題ごと黙らせるのは間違いになる。操舵室で×が出た日に「あの中に
      カロンがいる、私じゃない」と言うのは、まさに全員が言いたいことで、
      それを1人しか言えないようにしたら不自然になってしまう。
      そこで、話題の重複は許したまま、★同じ文が2人から出ることだけを防ぐ。
      （初日の朝の build_day1_clauses が既にこの方式を採っている）

    ★比べるのは書式を埋める前の「型」の方（"{p}は白だと思う。"）。
      埋めた後の文で比べると、名前が違うだけの「Bは白だと思う」「Cは白だと
      思う」がすり抜けてしまうが、人間が読んで気づくのは名前ではなく型の方。

    spoken    : その日すでに使われた文の集合。★選んだ文をここに書き足すので、
                呼び出す側は1日ぶん同じ集合を持ち回ること。
    allow_none: プールを使い切った時の振る舞い。
                  True  … None を返す（＝この話題には触れずに済ませる）。
                          何人も同じ部屋にいて全員が同じことを言う類の部品向け。
                  False … やむを得ず重複を許して普通に選ぶ。
                          ここで黙ると発言が成立しなくなる部品向け。
    """
    if not pool:
        return None
    fresh = [t for t in pool if t not in spoken]
    if not fresh:
        if allow_none:
            return None
        fresh = list(pool)
    choice = rng.choice(fresh)
    spoken.add(choice)
    return choice


