def build_fact_clauses(yesterday_destinations, yesterday_x_count, my_name, rng):
    """
    前日の公開結果から、事実整理の文を組み立てる。
    ここで使うのは誰でも見られる情報だけなので、どの役職が言っても安全。

    my_name は自分自身を「E・Iは行ってない」のような第三者的な
    名指しから除外するためだけに使う（不自然さを避けるための演出上の
    処理で、証拠としての意味は無い）。
    """
    if not yesterday_destinations:
        return []

    bridge = sorted(p for p, d in yesterday_destinations.items() if d == "操舵室")
    absent = sorted(p for p, d in yesterday_destinations.items() if d != "操舵室" and p != my_name)
    clauses = []

    if bridge:
        clauses.append(rng.choice(FACT_BRIDGE_MEMBERS).format(
            members="・".join(bridge), n=len(bridge)))

        if yesterday_x_count:
            clauses.append(rng.choice(FACT_X_APPEARED).format(x=yesterday_x_count))
        else:
            clauses.append(rng.choice(FACT_ALL_CLEAN))

        if len(bridge) <= 5:
            clauses.append(rng.choice(FACT_NAVIGATOR_LOGIC))

    if absent and len(absent) <= 3:
        clauses.append(rng.choice(FACT_ABSENT).format(absent="・".join(absent)))

    return clauses


def _weighted_pick_near_top(scored_desc, margin, rng):
    """
    降順に並んだ(名前, スコア)のリストから、一番高いスコアの人だけでなく、
    そこからmargin以内にいる人たちも候補に含め、スコアに応じた重み付き
    抽選で1人選ぶ（SUSPECT_NAME_MARGIN参照）。
    """
    top_score = scored_desc[0][1]
    cluster = [(p, s) for p, s in scored_desc if s >= top_score - margin]
    weights = [s for _, s in cluster]
    if sum(weights) <= 0:
        return rng.choice(cluster)[0]
    return rng.choices([p for p, _ in cluster], weights=weights, k=1)[0]


def _pick_near_bottom(scored_desc, margin, rng):
    """一番怪しくない人からmargin以内にいる人たちの中から、均等に1人選ぶ"""
    bottom_score = scored_desc[-1][1]
    cluster = [p for p, s in scored_desc if s <= bottom_score + margin]
    return rng.choice(cluster)


