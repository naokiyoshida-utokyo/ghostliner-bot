def build_day1_clauses(spoken, rng, library_on=True):
    """
    初日の朝に話す候補を返す（1グループにつき最大1文。DAY1_GROUPS参照）。

    spoken     : その日すでに誰かが言った文の集合。同じ文が2人から出ないよう
                 に除外する（初日は話題名ではなく文そのもので重複を管理する。
                 理由はDAY1_GROUPSのコメント）。
    library_on : 図書室を使うルールか。Falseなら図書室に触れる文を全部外す。
    """
    out = []
    for group in DAY1_GROUPS:
        lines = group
        if not library_on:
            lines = [line for line in group if "図書室" not in line]
            if group is DAY1_FLAVOR_LINES:
                lines = lines + DAY1_NO_LIBRARY_FLAVOR

        # ★グループ単位の人数制限（DAY1_GROUP_MAX_SPEAKERS のコメント参照）。
        #   文が違っても中身が同じなので、文の重複だけを見ても足りない。
        if sum(1 for line in lines if line in spoken) >= DAY1_GROUP_MAX_SPEAKERS:
            continue

        remaining = [line for line in lines if line not in spoken]
        if remaining:
            out.append(rng.choice(remaining))
    return out


def _night_reason(target, framing, today_destinations, today_x_count, rng, spoken,
                  persona=None):
    """
    夜の一言の「理由」部分を1つ選ぶ。
    framing: "suspect" か "trust"
    可能なら、今日の操舵室の公開結果からその対象について言える理由を
    優先し、無ければ「印象の説明」でぼかす。

    spoken : その日すでに使われた文の集合（_pick_fresh 参照）。
             ★ここは重複が一番目立っていた場所で、実測では夜の全文のうち
               「言ってることが一貫してるから。」が6.3%、「特に怪しい動きが
               無いから。」が6.7%＝この2文だけで夜の1割強を占めていた。
    persona: 話し手の職業。★印象の説明の部分を職業ごとの語彙に差し替える
             （PERSONA_REASON_SUSPECT / _TRUST 参照）。これが枯渇の対策と
             個性づけを同時に行っている部分。知らない職業ならGENERICに戻る。

    ★操舵室の結果から言う理由（NIGHT_REASON_BRIDGE_* など）は職業別にしない。
      あれは「昨日操舵室にいて×が出た」という誰が見ても同じ事実の指摘なので、
      職業ごとに言い換えると、かえって同じ事実の言い方が無駄に増える。
      職業色を出すのは、事実で説明できない「印象」の部分だけに絞っている。
    """
    pool = []
    if today_destinations and target in today_destinations:
        was_on_bridge = today_destinations[target] == "操舵室"
        if framing == "suspect":
            if was_on_bridge and today_x_count:
                pool += NIGHT_REASON_BRIDGE_X
            elif not was_on_bridge:
                pool += NIGHT_REASON_ABSENT
        else:
            if was_on_bridge and not today_x_count:
                pool += NIGHT_REASON_BRIDGE_CLEAN

    # 事実で説明できない部分は、職業ごとの語彙で言う（知らない職業なら共通プール）
    if framing == "suspect":
        pool += PERSONA_REASON_SUSPECT.get(persona) or NIGHT_REASON_GENERIC_SUSPECT
    else:
        pool += PERSONA_REASON_TRUST.get(persona) or NIGHT_REASON_GENERIC_TRUST

    # 理由は「疑う／信じる」の文とセットで意味を成すので、使い切っても黙らない
    return _pick_fresh(pool, spoken, rng)


def generate_library_report_speech(talk_worlds, target, claimed_role, persona=None, rng=random):
    """
    図書室で確認した本人が、夜の議論の冒頭で話す宣言。
    「なぜその人を選んだか」「誰を見たか」「結果は何だったか」の3つを必ず含む。

    ★嘘をつくかどうかは decision.decide_library_report が役職ごとに決めるので、
      ここでは渡された claimed_role をそのまま話すだけでよい。
      （この関数は本当の役職を受け取らない＝嘘か本当かを知らない作りにしてある。
        知らなければ、うっかり嘘だと分かる言い方をしてしまう事故が起きない）

    ★「選んだ理由」は、確認する前の自分の見立て(talk_worlds)から決める。
      強く疑っていた相手なら「ずっと怪しいと思ってた」、白そうな相手なら
      「裏を取りたかった」になるので、発言と行動のつじつまが自然に合う。
      呼び出す側は、他の発言と同じ視点の使い分け（乗客のみ私的視点、
      それ以外は公開情報視点）で talk_worlds を渡すこと。
    """
    parts = []
    opener = _pick(PERSONA_OPENERS.get(persona, OPENERS), rng)
    if opener:
        parts.append(opener)

    score = suspicion_score(talk_worlds, target)
    if score >= 0.55:
        pool = LIBRARY_REPORT_REASON_SUSPECT
    elif score < 0.30:
        pool = LIBRARY_REPORT_REASON_CONFIRM
    else:
        pool = LIBRARY_REPORT_REASON_NEUTRAL

    parts.append(rng.choice(pool).format(p=target))
    parts.append(rng.choice(LIBRARY_REPORT_RESULT_LINES).format(role=claimed_role))
    return "".join(parts)


def _members_text(companions):
    """
    同室者の名前を並べた文字列。多すぎる時は代表数人＋「たち」にまとめる。

    ★上限を5人から3人に下げてある。AIの名前が「気象予報士AI」「将棋棋士AI」
      のような職業名になったため、5人並べると名前だけで50字を超えて、
      肝心の「×が2枚出た」という中身が読み飛ばされてしまうため。
      実運用は人間6＋AI3のような混合プレイなので、人間のニックネームも
      混ざってさらに伸びる。
    """
    if not companions:
        return None
    if len(companions) <= MEMBERS_TEXT_MAX:
        return "・".join(companions)
    return "・".join(companions[:MEMBERS_TEXT_MAX - 1]) + "たち"


def build_night_room_clause(my_dest, companions, attack_happened, x_count, rng, spoken):
    """
    ①② その日、自分と同じ部屋になった人へのポジティブ／ネガティブな言及。

    ★行先も操舵室の○×の内訳も、その日の昼に全員へ公開される情報なので、
      どの役職が話しても安全。カロンが「もちろん私じゃないよ」と付け足すのは
      ただの嘘であって、私的情報の漏洩ではない（人間陣営が同じことを
      言っても全く同じ文になるので、外からは区別できない）。

    my_dest        : 自分が実際に行った部屋（亡霊に上書きされた後の、公開される行先）
    companions     : 同じ部屋にいた生存者
    attack_happened: その日、攻撃が発生したか
    x_count        : その日の操舵室に出た×の枚数
    spoken         : その日すでに使われた文の集合（_pick_fresh 参照）

    ★ここは全部品の中で最も重複が出やすい。同じ部屋にいた人は全員が同じ
      材料（顔ぶれ・×の枚数・攻撃の有無）から喋るので、9人卓の操舵室では
      7人が3種類の文を取り合うことになる。実測では9人中5人が一字一句
      同じ文を言っていた。そこで、プールを使い切ったら★部屋の話には
      触れずに済ませる（allow_none=True）。夜の発言は他に3つの部品が
      あるので、ここを1つ落としても喋れなくなることはない。
    """
    members = _members_text(companions)

    def choose(pool):
        return _pick_fresh(pool, spoken, rng, allow_none=True)

    if my_dest == "図書室":
        return choose(NIGHT_ROOM_LIBRARY)

    if my_dest == "操舵室":
        if x_count:
            pool = ([t for t in NIGHT_ROOM_BRIDGE_X if "{members}" not in t]
                    if members is None else NIGHT_ROOM_BRIDGE_X)
            template = choose(pool)
            return template.format(members=members, n=x_count) if template else None
        if members is None:
            return None
        template = choose(NIGHT_ROOM_BRIDGE_CLEAN)
        return template.format(members=members) if template else None

    if my_dest == "談話室":
        if attack_happened:
            pool = ([t for t in NIGHT_ROOM_LOUNGE_ATTACK if "{members}" not in t]
                    if members is None else NIGHT_ROOM_LOUNGE_ATTACK)
            template = choose(pool)
            return template.format(members=members) if template else None
        if members is None:
            return None
        template = choose(NIGHT_ROOM_LOUNGE_SAFE)
        return template.format(members=members) if template else None

    return None


def build_night_report_clause(role, talk_worlds, library_reports, my_name, ally_names,
                              alive, rng, spoken):
    """
    ③ 図書室での役職確認への言及（一番新しい報告に反応する）。

    ★漏洩対策は build_report_trust_clause と同じ考え方：
        ・自分が名指しされたら否定する（役職を問わず誰でもやる自然な反応）
        ・カロン陣営は、仲間を名指しした報告も否定する（＝正しい告発を
          否定するので、精度が高すぎて怪しまれる心配がない）
        ・仲間を白だと言ってくれた報告には乗っかる
        ・それ以外は、報告者が今どれくらい怪しく見えるかで決める
          （公開情報だけを見た、誰でもできる判断）
      ★どのプールを使うかの判断（＝漏洩対策の本体）は一切変えていない。
        変えたのは「選んだプールの中からどう1つ選ぶか」だけ。

    spoken: その日すでに使われた文の集合（_pick_fresh 参照）。
            ★1つの報告に何人もが反応するので重複しやすい。ただし
              「自分が名指しされた／白だと言われた」場合は、名指しされる
              のがその日1人だけなので他人と衝突しない＆黙ると否定しそこねる
              ため、使い切っても必ず何か言う（allow_none=False）。
    """
    if not library_reports:
        return None

    latest_day = max(library_reports)
    # ★脱落した人が絡む報告には触れない（もう吊れないし、庇う意味も無い）
    alive_set = set(alive) if alive else None
    reports = [r for r in library_reports[latest_day]
               if r["reporter"] != my_name
               and (alive_set is None
                    or (r["reporter"] in alive_set and r["target"] in alive_set))]
    if not reports:
        return None
    report = rng.choice(reports)

    reporter, target, claimed = report["reporter"], report["target"], report["claimed_role"]
    accuses_charon = claimed in engine.CHARON_SIDE
    protected = {my_name}
    if role in engine.CHARON_SIDE:
        protected |= set(ally_names or ())

    def say(pool, allow_none):
        template = _pick_fresh(pool, spoken, rng, allow_none=allow_none)
        if not template:
            return None
        return template.format(reporter=reporter, target=target, claimed=claimed)

    # 自分自身が確認された時は、三人称で自分の話をしないよう専用の言い方にする
    if target == my_name:
        pool = NIGHT_REPORT_DOUBT_ACCUSED_ME if accuses_charon else NIGHT_REPORT_CLEARED_ME
        return say(pool, allow_none=False)

    if target in protected and accuses_charon:
        return say(NIGHT_REPORT_DOUBT, allow_none=True)

    # 味方を白だと言ってくれた報告には、素直に乗っかっておく
    if target in protected and not accuses_charon:
        return say(NIGHT_REPORT_ACCEPT_CLEAN, allow_none=True)

    if suspicion_score(talk_worlds, reporter) >= 0.55:
        return say(NIGHT_REPORT_DOUBT, allow_none=True)

    pool = NIGHT_REPORT_ACCEPT_BLACK if accuses_charon else NIGHT_REPORT_ACCEPT_CLEAN
    return say(pool, allow_none=True)


def build_night_opinion_clause(talk_worlds, players, my_name,
                               today_destinations, today_x_count, rng, spoken,
                               persona=None, grudge=None):
    """
    「誰を、どういう理由で信用／疑っているか」の一言（従来からある部分）

    spoken: その日すでに使われた文の集合（_pick_fresh 参照）。
            ★これは各人の推理の結論そのものなので、使い切っても黙らせない
              （allow_none=False）。誰を疑っているかを言わないAIは、
              人間から見て判断材料が無さすぎる。
    """
    others = [p for p in players if p != my_name]
    if not others:
        return None

    # ★敵対心の下駄（decision.GRUDGE_* 参照）。朝と同じ扱い。
    grudge = grudge or {}
    scored = sorted(((p, min(1.0, suspicion_score(talk_worlds, p) + grudge.get(p, 0.0)))
                     for p in others),
                    key=lambda x: x[1], reverse=True)
    top_score = scored[0][1]
    bottom_score = scored[-1][1]

    # 「疑いを話す」と「信頼を話す」、より差がはっきり出ている方を選ぶ
    if top_score >= 1 - bottom_score:
        target = _weighted_pick_near_top(scored, SUSPECT_NAME_MARGIN, rng)
        line = _pick_fresh(NIGHT_SUSPECT_LINES, spoken, rng).format(p=target)
        reason = _night_reason(target, "suspect", today_destinations, today_x_count,
                               rng, spoken, persona)
    else:
        target = _pick_near_bottom(scored, TRUST_NAME_MARGIN, rng)
        line = _pick_fresh(NIGHT_TRUST_LINES, spoken, rng).format(p=target)
        reason = _night_reason(target, "trust", today_destinations, today_x_count,
                               rng, spoken, persona)

    return f"{line}{reason}"


def build_night_vote_clause(talk_worlds, alive_players, my_name, persona, rng, spoken,
                            grudge=None):
    """
    ④ 今日の投票をどうするつもりかの一言。
    投票結果はこの直後に全員へ公開されるので、予告しても情報の損はない
    （人間プレイヤーにとっては、AIの動きを読む手がかりになる）。
    確信が薄いうちは「まだ決めてない」と濁す。

    spoken: その日すでに使われた文の集合（_pick_fresh 参照）。
            ★誰に入れるつもりかは人間がAIの動きを読むための材料なので、
              使い切っても黙らせない（allow_none=False）。
    """
    others = [p for p in alive_players if p != my_name]
    if not others:
        return None

    grudge = grudge or {}   # ★敵対心の下駄（投票予告にも効かせる）
    scored = sorted(((p, min(1.0, suspicion_score(talk_worlds, p) + grudge.get(p, 0.0)))
                     for p in others),
                    key=lambda x: x[1], reverse=True)
    threshold = VOTE_TALK_THRESHOLD + PERSONA_CONFIDENCE_SHIFT.get(persona, 0.0)
    if scored[0][1] < threshold:
        pool = PERSONA_VOTE_UNSURE.get(persona) or NIGHT_VOTE_UNSURE
        return _pick_fresh(pool, spoken, rng)
    target = _weighted_pick_near_top(scored, SUSPECT_NAME_MARGIN, rng)
    pool = PERSONA_VOTE_INTENT.get(persona) or NIGHT_VOTE_INTENT
    return _pick_fresh(pool, spoken, rng).format(p=target)


def build_endgame_clause(role, board, rng, spoken):
    """
    どちらかの陣営が勝利ptに届いた日の、夜の議論の一言（普段は None）。

    ★勝敗の判定は「その夜の追放が終わってから」なので、勝利ptに届いた日でも
      まだ決着していない。夜の議論はその最後の攻防になる。
      判定順（1.カロン0人 → 2.カロン過半 → 3.○pt → 4.×pt）に従って、
      いま何が起きているのかを喋らせる。ENDGAME_* のコメントも参照。

    ★使う情報は ○pt/×pt と「今日の操舵室に出た×の枚数」だけ。
      どれも全員が見て分かる公開情報なので、どの役職が喋っても漏洩にならない。
      唯一の例外が ENDGAME_X_LOCKED_CHARON（カロンの勝利宣言）で、これは
      ★カロン陣営の勝ちがすでに確定している場合にだけ出す。吊られても
      結果が変わらないので、正体を明かして構わない。
    """
    c_pt = board.get("c_pt")
    x_pt = board.get("x_pt")
    win_c = board.get("win_c")
    win_x = board.get("win_x")
    today_x = board.get("today_x_count") or 0

    # ★○ptの判定が×ptより先に行われるので、両方届いていたら人間陣営の勝ち
    if win_c and c_pt is not None and c_pt >= win_c:
        return _pick_fresh(ENDGAME_C_REACHED, spoken, rng)

    if win_x and x_pt is not None and x_pt >= win_x:
        # ★×を出せるのはカロンだけ。今日の操舵室に×が2枚出たということは、
        #   カロンが2人その場にいた＝2人とも生きている（操舵室にいた人は
        #   その日の攻撃で死なない）。今夜1人吊ってもカロンは0人にならない
        #   ので、この時点でカロン陣営の勝ちが確定している。
        if today_x >= 2:
            pool = (ENDGAME_X_LOCKED_CHARON if role in engine.CHARON_SIDE
                    else ENDGAME_X_LOCKED_HUMAN)
            return _pick_fresh(pool, spoken, rng)
        # ×が1枚なら、カロンが1人だけ残っている可能性がある＝まだ望みがある。
        # ★カロン陣営もこれを言う（ここで正体を明かすと吊られて負けるため）。
        return _pick_fresh(ENDGAME_X_LAST_CHANCE, spoken, rng)

    return None


def generate_night_comment(talk_worlds, players, my_name, role=None, ally_names=(),
                           board=None, persona=None, spoken_lines=(), rng=random,
                           grudge=None):
    """
    夜の議論で喋る発言（朝のひとり言と同じくらいの量）。

    ★戻り値: (発言テキスト or None, 今回使った文の集合)
      以前はテキストだけを返していたが、同じ日に同じ文が何人からも出るのを
      防ぐため、朝の generate_monologue と同じ「使ったものを呼び出し側へ
      返して持ち回る」形に揃えた。

    次の話題からいくつかを選んで組み立てる：
      ①② その日、自分と同じ部屋になった人への言及（良い方向・悪い方向）
      ③   図書室での役職確認への言及
      ④   今日の投票をどうするつもりか
      ＋  誰を、どういう理由で信用／疑っているか（従来からある部分）

    talk_worlds: 発言のもとになる信念状態
                 （乗客のみ私的視点、それ以外は公開情報視点。
                   呼び出し側はgenerate_monologueと同じ使い分けをすること）
    role       : 本当の役職（③で仲間を庇うかどうかの判断に使う）
    ally_names : 自分が知っている仲間（同上）
    board      : 盤面の公開情報。使うのは次のキー：
                   "today_destinations": 今日の {プレイヤー: 行先}
                   "today_x_count"     : 今日の操舵室に出た×の枚数
                   "attack_happened"   : 今日、攻撃が起きたか
                   "alive"             : 生存者のリスト
                   "library_reports"   : {日付: [{reporter, target, claimed_role}]}
                   "library_on"        : 図書室を使うルールか（Falseなら図書室に触れない）
    spoken_lines: その日すでに他の人が使った文の集合。呼び出す側は、戻り値の
                  2つ目を足し込みながらその日の残りの呼び出しに渡すこと
                  （_pick_fresh のコメントに、なぜ話題ではなく文の単位で
                    重複を見るのかを書いてある）。

    ※亡霊は発言禁止なので、呼び出す側でそもそも亡霊には呼ばないでください。
    """
    board = board or {}
    today_dest = board.get("today_destinations") or {}
    today_x = board.get("today_x_count")
    alive = board.get("alive") or players
    my_dest = today_dest.get(my_name)
    companions = sorted(p for p in alive
                        if p != my_name and today_dest.get(p) == my_dest)

    # その日すでに使われた文。★ここで作った作業用の集合に各部品が選んだ文を
    #   書き足していき、最後に「今回ぶんだけ」を切り出して呼び出し側へ返す。
    spoken = set(spoken_lines)
    before = set(spoken)

    parts = []
    opener = _pick(PERSONA_OPENERS.get(persona, OPENERS), rng)
    if opener:
        parts.append(opener)

    # ★どちらかの陣営が勝利ptに届いた日は、その話を必ず最初にする。
    #   普段どおり「誰が怪しい」から入ると、状況が分かっていない人に見える。
    endgame = build_endgame_clause(role, board, rng, spoken)
    if endgame:
        parts.append(endgame)

    # 図書室を使わないルールでは、図書室の報告そのものが存在しない
    library_reports = board.get("library_reports") if board.get("library_on", True) else None

    pool = []
    for clause in (
        build_night_room_clause(my_dest, companions,
                                board.get("attack_happened"), today_x, rng, spoken),
        build_night_report_clause(role, talk_worlds, library_reports,
                                  my_name, ally_names, alive, rng, spoken),
        # ★生きている人の中から選ぶ（players には脱落者も入っている）
        build_night_opinion_clause(talk_worlds, alive, my_name,
                                   today_dest, today_x, rng, spoken, persona,
                                   grudge=grudge),
        build_night_vote_clause(talk_worlds, alive, my_name, persona, rng, spoken,
                                grudge=grudge),
    ):
        if clause:
            pool.append(clause)

    if not pool:
        return (("".join(parts) or None), spoken - before) if endgame else (None, set())

    # ★決着間近の話をした日は、それが発言の主役。普段の雑談は少なめにする
    #   （長々と喋ると、いちばん大事な一言が埋もれてしまう）。
    if endgame:
        take = min(len(pool), rng.randint(1, 2))
    else:
        take = min(len(pool), rng.randint(NIGHT_CLAUSE_MIN, NIGHT_CLAUSE_MAX))
    chosen = sorted(rng.sample(range(len(pool)), take))
    parts.extend(pool[i] for i in chosen)

    hedge = _pick(PERSONA_HEDGES.get(persona, HEDGES), rng)
    if hedge:
        parts.append(hedge)

    text = "".join(parts)
    # ★実際に喋らなかった部品の文も「使った」ことにして返している。
    #   組み立ててから枠の都合で落とすため、どの文が最終的に残ったかを
    #   後から型に戻して特定できないため。多めに避けることになるが、
    #   その分だけ後の人の言い回しが散る方向にしか働かないので害は無い。
    return (text if text else None), spoken - before


# ============================================================
# まとめ：1人ぶんのひとり言を組み立てる
# ============================================================

def generate_monologue(
    role, talk_worlds, players, my_name, my_actual_dest,
    ally_names=(), board=None,
    suspected_yesterday=None, wanted_library=False, spoken_topics=(),
    prior_suspect=None, persona=None, rng=random, grudge=None,
):
    """
    その日このプレイヤーが喋るひとり言を返す（喋らない日は None）。

    戻り値: (発言テキスト or None, 今回話した話題の集合, 疑いを名指ししたか(相手 or None))

    複数の「部品」をランダムに選んで数個つなげることで、
    毎回違う文章になるようにしている（部品の組み合わせなので、
    LLMを使わなくても十分な多様性が出る）。

    grudge                : この人が今持っている敵対心 {相手: 強さ}。
                            誰を名指しで疑うかにだけ効く（decision.GRUDGE_* 参照）。
    role                  : 本当の役職
    talk_worlds           : 発言のもとになる信念状態
                            （乗客のみ私的視点、それ以外は公開情報視点）
    my_actual_dest        : その日、実際に決まった行先。
                            ★呼び出す側は、その日の行先が全員分決まってから
                              この関数を呼んでください（図書室の立候補結果を
                              含めて、実際の予定を話せるようにするため）。
    ally_names            : 自分が知っている仲間の名前。★漏れ★で使う
                            （航海士なら相方の航海士、カロンなら相方のカロン、
                              セイレーンなら知っているカロンたち）
    board                 : 盤面の公開情報をまとめた辞書。全員が見て分かる
                            情報だけを入れること（私的情報は絶対に入れない）。
                              "day"              : 今日が何日目か。1（初日）のときだけ
                                                   専用のセリフに切り替わる（DAY1_GROUPS参照）
                              "library_on"       : 図書室を使うルールか。Falseなら
                                                   図書室の話題を一切出さない
                              "destinations"     : {日付: {プレイヤー: 行先}} の全履歴
                              "yesterday_x_count": 前日の操舵室に出た×の枚数
                              "votes"            : 前日の {投票者: 投票先 or None}
                              "exiled"           : 前日に追放された人（いなければNone）
                              "deaths"           : 前日の [(脱落者, "攻撃"/"返り討ち")]
                              "c_pt"/"x_pt"      : 現在の○pt・×pt
                              "win_c"/"win_x"    : 勝利に必要な○pt・×pt
                              "alive"            : 生存者のリスト
                              "library_idle"     : 前日、誰も図書室に行かなかったか
                              "library_left"     : まだ図書室カードを持つ人がいるか
                              "library_reports"  : {日付: [{reporter, target, claimed_role}]}
                                                   （宣言された内容そのもの。本当か
                                                     嘘かの情報は入っていない）
    suspected_yesterday   : 自分が前日に名指しで疑った相手（心変わりの表現に使う）
    wanted_library        : その日、図書室に立候補したか（結果的に行けたかは問わない）。
                            人間プレイヤーが「このAIは図書室を狙っていそうだ／
                            誰も図書室に行かなそうだ」と空気を読めるようにするための情報。
    spoken_topics         : その日、すでに他の人が話した話題の集合（TOPIC_*）。
                            ★同じ日に何人もが同じ公開情報の要約を独立に繰り返すと、
                              テンプレを読んでいるような不自然さが強く出る
                              （実際に確認済み：8人中7人が同じ内容を言う事例が
                              発生していた）。しかもこれらの話題は盤面を見れば
                              人間にも分かる情報なので、繰り返す価値が薄い。
                              その日最初に話した人だけがその話題を話し、以降は
                              省略して、代わりに「誰を疑っているか」「今日の予定」
                              という個人差の出る部分に文字数を回す。
                              呼び出す側は、戻り値の2つ目（話した話題の集合）を
                              足し込みながら、その日の残りの呼び出しに渡すこと。
                              （図書室の呼びかけだけは例外で、重複を許している。
                                複数人が「誰か行こうよ」と言うのは自然なため）
    prior_suspect          : その日、直前までに誰かが名指しした疑いの相手（③）。
                            呼び出す側は、戻り値の3つ目がNoneでなければ、
                            その日の残りの呼び出しにはその値を渡すこと
                            （＝会話が一番新しい発言に反応していく形になる）。
    persona                : この人が使う口調（PERSONA_NAMES参照。Noneや
                            未知の値なら「ニュートラル」＝元の共通プールになる）。
                            ★口調のみに影響し、話す内容（誰を疑うか・どこに
                              行くか）には一切影響しない。呼び出す側は、
                              同じプレイヤーには1ゲームを通して同じ値を
                              渡し続けること（日によって口調が変わると
                              不自然なため）。

    ※亡霊は「発言やジェスチャーは禁止」なので、呼び出す側で
      そもそも亡霊にはこの関数を呼ばないでください。
    """
    if rng.random() >= SPEAK_PROBABILITY:
        return None, set(), None

    board = board or {}
    spoken = set(spoken_topics)
    openers_pool = PERSONA_OPENERS.get(persona, OPENERS)
    hedges_pool = PERSONA_HEDGES.get(persona, HEDGES)

    parts = []

    # 前置き
    opener = _pick(openers_pool, rng)
    if opener:
        parts.append(opener)

    # 盤面の公開情報を取り出す（前日の行先は履歴の最終日ぶん）
    history = board.get("destinations") or {}
    yesterday_dest = history[max(history)] if history else None

    # ★図書室を使わないルール（7人プレイなど）では、図書室の話を一切しない。
    #   特に「昨日は誰も図書室に行かなかったね」は、図書室が無いルールだと
    #   毎日必ず条件を満たしてしまうので、放っておくと連日それを言い続ける。
    library_on = board.get("library_on", True)
    if not library_on:
        # 「図書室を狙っていたが譲った」の文も出ないようにする（保険。
        #  そもそも図書室が無ければ立候補は起きない）
        wanted_library = False

    # 本体になりうる話題を (話題名, 文) の形で集める。
    # 話題名が付いているものは「その日1人しか話さない」対象。
    # 話題名が None のものは個人の意見なので、何人が話してもよい。
    body_pool = []
    inference = None
    suspect_mention = None

    # ---- 初日は、まるごと専用のセリフに差し替える ----
    # 材料になる前日の出来事がまだ何も無いため。詳しくはDAY1_GROUPSのコメント。
    if board.get("day") == 1:
        # 話題名の代わりに文そのものを入れて、同じ文が2人から出ないようにする
        body_pool = [(line, line)
                     for line in build_day1_clauses(spoken, rng, library_on=library_on)]
        return _finish_monologue(
            parts, body_pool, DAY1_CLAUSE_MIN, DAY1_CLAUSE_MAX,
            role, ally_names, hedges_pool, my_actual_dest, wanted_library,
            inference=None, suspect_mention=None, rng=rng, first_day=True,
            persona=persona, spoken=spoken)

    if TOPIC_FACT not in spoken:
        for clause in build_fact_clauses(
                yesterday_dest, board.get("yesterday_x_count"), my_name, rng):
            body_pool.append((TOPIC_FACT, clause))

    if TOPIC_VOTE not in spoken:
        clause = build_vote_clause(board.get("votes"), board.get("exiled"), my_name, rng)
        if clause:
            body_pool.append((TOPIC_VOTE, clause))

    if TOPIC_DEATH not in spoken:
        clause = build_death_clause(board.get("deaths"), rng)
        if clause:
            body_pool.append((TOPIC_DEATH, clause))

    if TOPIC_POINTS not in spoken:
        clause = build_points_clause(
            board.get("c_pt", 0), board.get("x_pt", 0),
            board.get("win_c"), board.get("win_x"), rng)
        if clause:
            body_pool.append((TOPIC_POINTS, clause))

    if TOPIC_STREAK not in spoken:
        clause = build_streak_clause(
            history, board.get("alive") or players, my_name, rng)
        if clause:
            body_pool.append((TOPIC_STREAK, clause))

    # 以下は個人の意見なので、何人が話してもよい（話題名を付けない）。
    if library_on:
        # 図書室の呼びかけ（複数人が「誰か行こうよ」と言うのは自然）
        # ★話題名の代わりに「文そのもの」を入れる（初日の朝と同じ方式）。
        #   こうすると、実際にその文が選ばれた時だけ used_topics に乗って
        #   次の発言者に伝わり、同じ文が2人から出るのを防げる。
        #   話題としての重複は今まで通り許しているので、別の言い回しが
        #   残っていれば何人でも「図書室に行こうよ」と言える。
        clause = build_library_call_clause(
            board.get("library_idle"), board.get("library_left"), rng, spoken)
        if clause:
            body_pool.append((clause, clause))

        # 図書室で誰を確認してほしいか（★役職ごとの分岐あり。関数のコメント参照）
        clause = build_library_nominate_clause(
            role, talk_worlds, my_name, board.get("alive") or players,
            ally_names, board.get("library_left"), rng, spoken=spoken)
        if clause:
            body_pool.append((None, clause))

        # 図書室に行った人の報告を信用するか（★役職ごとの分岐あり）
        clause = build_report_trust_clause(
            role, talk_worlds, board.get("library_reports"), my_name, ally_names, rng,
            alive=board.get("alive") or players)
        if clause:
            body_pool.append((None, clause))

    # ★推論も「文そのもの（書式を埋める前の型）」を話題名にして、実際に
    #   選ばれた時だけ次の発言者に伝わるようにする（図書室の呼びかけと同じ方式）。
    #   話題としての重複は今まで通り許す＝何人が推論を語ってもよいが、
    #   同じ言い回しは1日1人までになる。
    # ★カロン陣営は、カロンを追い詰める指摘を確率で飲み込む
    #   （CHARON_SILENCE_RATE のコメント参照）。ここで黙ったぶんは、
    #   人間陣営と同じ話題プールから自動的に埋め合わされる。
    def _speaks_up():
        if role in engine.CHARON_SIDE:
            return rng.random() >= CHARON_SILENCE_RATE
        return True

    # ★証拠から絞り込んだ集合の話（「この中にカロンがいる」「この2人のどっちか」）。
    #   確率の読み上げではなく推理の筋道に聞こえるので、いちばん人間らしく響く部品。
    if _speaks_up():
        clause, key = build_evidence_group_clause(
            talk_worlds, board, my_name, board.get("alive") or players, rng, spoken)
        if clause:
            body_pool.append((key, clause))

    # ★ライン（カロン陣営同士の庇い合い）の指摘。図書室がある卓だけ
    if library_on and _speaks_up():
        clause, key = build_line_clause(
            talk_worlds, board, my_name, board.get("alive") or players, rng, spoken,
            ally_names=ally_names)
        if clause:
            body_pool.append((key, clause))

    # ★「もし操舵室以外に行ったらカロン確定」という条件付きの予想
    if _speaks_up():
        clause, key = build_conditional_clause(
            talk_worlds, my_name, board.get("alive") or players, rng, spoken,
            ally_names=ally_names)
        if clause:
            body_pool.append((key, clause))

    inference, suspect_mention, inference_key = build_inference_clause(
        talk_worlds, players, my_name, rng, prior_suspect=prior_suspect,
        persona=persona, spoken=spoken,
        day=board.get("day", 1), alive=board.get("alive"), ally_names=ally_names,
        grudge=grudge)
    if inference:
        body_pool.append((inference_key, inference))

    # ★前日に疑っていた相手がもう脱落しているなら、心変わりの話はしない
    alive_now = board.get("alive") or players
    if suspected_yesterday is not None and suspected_yesterday not in alive_now:
        suspected_yesterday = None
    if rng.random() < WAVER_RATE:
        waver = build_waver_clause(suspected_yesterday, rng)
        if waver:
            body_pool.append((None, waver))

    return _finish_monologue(
        parts, body_pool, CLAUSE_MIN, CLAUSE_MAX,
        role, ally_names, hedges_pool, my_actual_dest, wanted_library,
        inference=inference, suspect_mention=suspect_mention, rng=rng,
        inference_key=inference_key, persona=persona, spoken=spoken)


def _finish_monologue(parts, body_pool, clause_min, clause_max,
                      role, ally_names, hedges_pool,
                      my_actual_dest, wanted_library,
                      inference, suspect_mention, rng,
                      first_day=False, inference_key=None,
                      persona=None, spoken=None):
    """
    集めた候補から実際に喋る文を選んで、1つの発言に組み立てる。
    （通常の日と初日で候補の集め方だけが違い、ここから先は共通）

    spoken: その日すでに使われた文の集合。★「今日の予定」の文はここで
            選ぶので、選んだものを呼び出し側へ返す必要がある（予定は
            body_pool を通らず必ず喋られるため、話題名では拾えない）。
            下の plan_before との差分を used_topics に足して返している。
    """
    # ★初日だけは本文が0でも先へ進む。
    #   話題の上限（DAY1_GROUP_MAX_SPEAKERS）で候補が尽きた人がここに来るが、
    #   ここで返してしまうと黙ってしまう（「必ず毎日喋る」方針に反する）。
    #   下の保険が「予定だけの短い発言」を必ず作るので、そこまで進ませる。
    if not body_pool and not first_day:
        return None, set(), None

    spoken = spoken if spoken is not None else set()
    plan_before = set(spoken)

    # ---- 今日の予定は、先に作っておく ----
    # ★以前はこれを必ず・必ず発言の最後に付けていたため、その日の発言が
    #   全員そっくりな型で終わっていた（ROOM_DILEMMA_RATE のコメント参照）。
    #   ここでは「そもそも言うかどうか」を build_plan_clause に任せ、
    #   言う場合も「冒頭か末尾か」を確率で決める。
    plan = build_plan_clause(role, my_actual_dest, wanted_library, rng,
                             persona=persona, spoken=spoken)
    plan_first = bool(plan) and rng.random() < PLAN_FIRST_RATE
    if plan_first:
        # 前置きの直後、本文より前に置く
        parts.append(plan)

    # 候補から数個をランダムに選ぶ。
    # ★以前は先頭から機械的に取っていたため、事実整理が複数生成された日は
    #   常にそれだけで枠が埋まり、推論（誰を疑うか）が一切喋られない
    #   ことがあった。ランダムに選ぶことでその偏りを無くす。選ばれた話題は
    #   元の並び順のまま繋げるので、読む時の自然さは保たれる。
    take = min(len(body_pool), rng.randint(clause_min, clause_max))
    chosen_indices = sorted(rng.sample(range(len(body_pool)), take))
    chosen = [body_pool[i] for i in chosen_indices]
    parts.extend(text for _topic, text in chosen)

    # 実際に選ばれた話題だけを呼び出し側へ返す
    # （組み立てた候補が枠の都合で削られることがあるため）
    used_topics = {topic for topic, _text in chosen if topic is not None}
    said_suspect = (suspect_mention
                    if (inference and (inference_key, inference) in chosen)
                    else None)

    # ★漏れ★ たまに、その役職しか知り得ない情報が混ざる
    leaked = False
    if rng.random() < LEAK_RATE:
        leak = build_leak_clause(role, ally_names, rng, first_day=first_day)
        if leak:
            parts.append(leak)
            leaked = True

    # 濁し
    # 初日の本文は推理ではなく事実や気持ちなので、「勘だけどね」と濁されると
    # 噛み合わない。★漏れ★が出た時だけ濁す（漏れは根拠のない断定なので、
    # そこを濁すのはむしろ自然）。
    hedge = ""
    if not first_day or leaked:
        hedge = _pick(hedges_pool, rng)
        if hedge:
            parts.append(hedge)

    # 今日の予定を末尾で言う場合はここ（冒頭で言う場合は上で済ませてある）
    if plan and not plan_first:
        parts.append(plan)

    # ★保険：本文が1つしか選ばれず、漏れも濁しも予定も出なかった日は、
    #   さすがに短すぎる。「無言のAIより、曖昧でも何か言う方がいい」という
    #   方針は変えていないので、その時だけ行先を濁す文を必ず足す。
    #   （ここに入るのは plan が None の時＝行先が図書室ではない時だけなので、
    #     図書室の予定と二重に喋ってしまう心配はない）
    # ★条件に not plan を足した理由：予定を既に言っている人にもう一度予定を
    #   足すと「今日は操舵室に行くよ。操舵室か談話室か迷ってる。」のように
    #   矛盾した発言になる。以前は本文が必ず1つ以上あったのでこの組み合わせに
    #   ならなかったが、初日に本文が0になり得るようになったため明示的に防ぐ。
    if not plan and (len(chosen) + int(leaked) + int(bool(hedge))) <= 1:
        filler = build_plan_clause(
            role, my_actual_dest, wanted_library, rng, force=True,
            persona=persona, spoken=spoken)
        if filler:
            parts.append(filler)

    # ★「今日の予定」で使った文も、呼び出し側に伝えて持ち回ってもらう。
    #   予定は body_pool を通らず必ず喋られるので、話題名では拾えない。
    #   ここで選んだものは確実に発言に入っているので、印を付けて正しい。
    used_topics |= (spoken - plan_before)

    text = "".join(parts)
    return (text if text else None), used_topics, said_suspect


def find_suspected_target(talk_worlds, players, my_name):
    """
    「前日に誰を疑っていたか」を記録するための補助。
    ゲーム進行側が毎日これを呼んで保存し、翌日 suspected_yesterday として
    渡すと、心変わりの表現が使えるようになる。
    """
    others = [p for p in players if p != my_name]
    if not others:
        return None
    return max(others, key=lambda p: suspicion_score(talk_worlds, p))


