def build_worlds(players, composition):
    """
    プレイヤー一覧と構成表を受け取って、
    ありうる配役パターン（＝世界）を全部つくって返す。

    返ってくるのは、こういう辞書のリスト（1つ1つが「世界」）：
        [
          {"roles": {"A": "航海士", "B": "航海士", "C": "カロン", ...}, "weight": 1.0},
          {"roles": {"A": "航海士", "B": "航海士", "C": "乗客",   ...}, "weight": 1.0},
          ...
        ]

    まだ何の証拠も見ていないので、全部の世界の weight は 1.0（横並び）です。
    """
    roles = list(composition.items())   # [("航海士", 2), ("カロン", 2), ...]

    def assign(remaining, decided, role_index):
        # 全部の役職を配り終えたら、1つの世界が完成
        if role_index == len(roles):
            yield {"roles": dict(decided), "weight": 1.0}
            return

        role_name, count = roles[role_index]

        # 残っているプレイヤーの中から count 人を選ぶ、その全通り
        for chosen in combinations(remaining, count):
            next_decided = decided + [(p, role_name) for p in chosen]
            next_remaining = [p for p in remaining if p not in chosen]
            # 次の役職へ（再帰）
            yield from assign(next_remaining, next_decided, role_index + 1)

    return list(assign(players, [], 0))


def make_players(n):
    """人数から A, B, C... のプレイヤー名リストをつくる"""
    return [chr(ord("A") + i) for i in range(n)]


# ============================================================
# 「自分は乗客だ」という前提で世界を絞った視点をつくる
# ============================================================

def view_as_passenger(worlds, my_name):
    """
    公開情報の世界(public_worlds)を、「my_name は乗客である」世界だけに
    絞った視点を返す。★これが GHOST LINER の発言の土台になる考え方です。

    ★なぜこれが必要か
      GHOST LINER では、航海士もカロンもセイレーンも、全員が「乗客のふり」を
      して喋ります。ところが公開情報だけの視点(public_worlds)には
      「自分が誰か」という情報すら入っていないので、そのままだと
      たとえばカロンは「あの2人のどちらかがカロンだ。自分はカロンでは
      ないのだから、相手の方だ」という、一番基本的な言い返しができません。
      （自分がカロンである世界も候補に残ったままなので、
        「自分ではない」と言い切れない）

    ★なぜ「乗客だと仮定する」だけで嘘が作れるのか
      人間陣営にとって、この仮定は嘘ではありません（航海士も
      「自分は白だ」と本気で思っている）。カロン陣営にとっては
      この仮定そのものが嘘なので、あとは正直に推理するだけで、
      結果が自動的に「相手の方がカロンだ」という主張になります。
      ★つまり、嘘を書くコードが1行も要りません。
        捏造した嘘は他の発言と必ずどこかで矛盾しますが、これは
        「本物の乗客がしたはずの推理」そのものなので、原理的に
        矛盾しません。

    ★メモリを増やさない作り
      新しい世界を作り直すのではなく、元の世界の辞書をそのまま指す
      リストを返します（中身のコピーはしない）。この視点は読むだけに
      使うので共有して問題ありません。本番は512MBのサーバなので、
      ここで世界を複製すると人数の上限が下がってしまいます。

    ★絞れなかった場合は元の視点をそのまま返します。
      公開情報から「この人は乗客ではありえない」と分かってしまった人
      （図書室で航海士だと暴かれた等）は、乗客のふりが成立しません。
      その場合は今まで通り public_worlds で喋らせます。
    """
    view = [w for w in worlds
            if w["weight"] > 0 and w["roles"].get(my_name) == "乗客"]
    if not view:
        return worlds
    return view


# ============================================================
# 確認用：各プレイヤーがある役職である割合を数える
# ============================================================

def role_ratio(worlds, player, role_name):
    """
    残っている世界のうち、
    「player が role_name になっている世界」の重みが何割を占めるかを返す。

    ★これが推理エンジンの答えの出し方そのものです。
      個数ではなく weight（重み）の合計で計算するのがポイントです。
      こうしておくと、rules.py が世界を weight=0 にして消したときも、
      weight が0.3のような中間値になったときも、同じ式でそのまま計算できます。

      いまはまだ何も削っていないので、全員同じ割合になるはずです。
      削り始めると、この数字が動きます。
    """
    total_weight = sum(w["weight"] for w in worlds)
    if total_weight == 0:
        return 0.0
    hit_weight = sum(w["weight"] for w in worlds if w["roles"][player] == role_name)
    return hit_weight / total_weight


