# 亡霊の妨害（行先を談話室に上書きする）
# ============================================================

def decide_ghost_overwrite(worlds, players, my_original_role, alive_players, blocked_today, rng=random):
    """
    亡霊が、誰かの行先を談話室に上書きするかどうかを決める。

    戻り値: 上書きする相手の名前、または妨害しないなら None

    考え方：
      ・人間側の亡霊：カロン/セイレーンをかなり高い確信度
        （GHOST_HUMAN_CONFIDENCE_THRESHOLD以上）で特定できているときだけ、
        GHOST_HUMAN_INTERFERE_RATE の確率で妨害する。
        「攻撃されそうな味方を談話室へ避難させて守る」という守り側の動きは
        実装していない（今回は見送り、攻め側だけを扱う）。
      ・カロン側の亡霊：人間陣営らしき人をランダムに1人選び、
        GHOST_CHARON_INTERFERE_RATE の確率で妨害する。○ptが増えるのを
        邪魔するのが狙い。仲間のカロンだと私的に分かっている相手は、
        妨害の対象から外す（妨害してもカロン陣営の得にならないため）。

      どちらも確率を低めにしてあります。理屈より、人間プレイヤーの
      体感を優先した値です（亡霊にガンガン妨害されるのは単純に不快なので）。

    my_original_role: 亡霊になる前の、本当の役職（"航海士" など）
    blocked_today    : 今日は妨害できない人の集合
                        （ルールブック：前日に妨害された人は、次の日は
                          どの亡霊からも妨害されない）
    """
    candidates = [p for p in alive_players if p not in blocked_today]
    if not candidates:
        return None

    if my_original_role in engine.HUMAN_SIDE:
        target = most_suspicious_player(worlds, candidates, rng=rng)
        if target is None or suspicion_score(worlds, target) < GHOST_HUMAN_CONFIDENCE_THRESHOLD:
            return None
        return target if rng.random() < GHOST_HUMAN_INTERFERE_RATE else None

    # カロン側の亡霊：私的に「仲間のカロン」だと分かっている相手は除外する
    human_side_candidates = [p for p in candidates if engine.role_ratio(worlds, p, "カロン") < 0.99]
    if not human_side_candidates:
        return None
    target = rng.choice(human_side_candidates)
    return target if rng.random() < GHOST_CHARON_INTERFERE_RATE else None


def decide_destination(role, tentative_dest, fallback_dest, declared_so_far, nominated_me):
    """
    朝の議論中、行先を最終的にどこにするかを決める（図書室の衝突回避版）。

    引数：
      role            : 自分の役職（"航海士" など）
      tentative_dest  : 今のところ自分が行こうと思っている行先
                         （"操舵室" / "図書室" / "談話室"）
      fallback_dest   : 図書室をゆずることになった場合の、代わりの行先
                         （本格的な「行先の決め方」自体はまだ作っていないので、
                           今回は外から渡してもらう前提にしています）
      declared_so_far : 自分以外のプレイヤーが、これまでに宣言した行先の一覧
                         （例: ["操舵室", "図書室"]。宣言は嘘の可能性がある
                           情報ですが、ここでは「衝突を避ける」ために使うだけ
                           なので、嘘かどうかは気にしません）
      nominated_me    : 自分が「図書室に行くべき」と指名されているか (bool)

    戻り値：
      実際にこのAIが選ぶ行先

    考え方：
      ・航海士は判断の余地なし。必ず操舵室（ルールブックの強制ルール）。
      ・図書室に行きたいと思っていても、すでに他の誰かが「図書室に行く」と
        宣言していたら、図書室カードは無駄になる可能性が高い
        （ルールブック：複数人が図書室に行くと誰も確認できない）。
        なので、自分が指名されているのでなければ、素直に譲る。
      ・自分が指名されているなら、先に宣言されていても強行してよい
        （指名した人たちとの合意がある、とみなす）。
    """
    if role == "航海士":
        return "操舵室"

    if tentative_dest == "図書室":
        someone_else_claimed_library = "図書室" in declared_so_far
        if someone_else_claimed_library and not nominated_me:
            return fallback_dest

    return tentative_dest


