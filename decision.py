def siren_plan_action(worlds, players, my_name, declared_so_far_dest, rng=random,
                      alive_players=None, bridge_need=0, deaths_count=0):
    """
    セイレーンが「行先・カード・呼び寄せ対象」をどうするかを決める。

    戻り値: (行先, カード, 呼び寄せ対象 or None)

    考え方（ユーザーの実プレイ経験にもとづく立ち回り）：
      ・セイレーンの仕事は2つ。「自分が図書室に行く」か、「朝の議論を聞いて、
        人間陣営が図書室に行きそうならその人を妨害する」。
      ・呼び寄せの一番の狙いは「図書室を機能不全にすること」です。
        （ルールブック「ハデスの基本」：図書室は人間陣営に使われるほど
          カロン陣営の不利になっていく）
        その日、図書室に行くと分かっている人間陣営がちょうど1人だけ
        見えているなら、SIREN_CHARM_RATEの確率でその人を操舵室へ
        呼び寄せて、図書室を空振りさせます。呼び寄せは操舵室からしか
        撃てないので、この日は必ず操舵室へ行きます。
      ・★妨害する相手がいない日は、操舵室と談話室を半々で選びます
        （SIREN_BRIDGE_WEIGHT）。カロン陣営が図書室に行きそうな日や、
        そもそも誰も行かなそうな日がこれにあたります。
        以前はここが「常に操舵室」になっていて、談話室に一度も行かないせいで
        人間から役職を絞られる状態でした（定数の説明を参照）。
      ・カロンの仲間（＝自分から見て確定でカロン側と分かっている相手）は
        呼び寄せの対象から除外します。仲間を図書室から引き剥がしても
        得がなく、不自然に目立つだけのためです。
      ・図書室に行くと2人以上見えている日も呼び寄せません。どのみち
        複数人が行けば図書室は自然に不成立になるので、撃つだけ無駄です。

    declared_so_far_dest：{プレイヤー名: 宣言した行先} の辞書
      （①で作った「行先宣言」の仕組みを利用しています）
      ★Discordでは人間の議論を読めないので、ここに入るのは「AIのうち
        図書室に行くと決まった人」だけになります。人間が図書室へ行くかは
        知りようがないので、その分だけ妨害の機会は減ります（割り切り）。
    """
    # 人数不足を狙う日は、呼び寄せもしないで談話室へ。
    # ★呼び寄せは相手を「操舵室へ」引っ張る能力なので、使うと操舵室の人数が
    #   1人増えてしまい、人数不足を自分で潰すことになる。
    if charon_side_seeks_shortage(worlds, alive_players, bridge_need,
                                  deaths_count=deaths_count, rng=rng):
        return "談話室", "c", None

    library_claimants = [
        p for p, dest in declared_so_far_dest.items()
        if dest == "図書室" and p != my_name and suspicion_score(worlds, p) < 1.0
    ]

    if len(library_claimants) == 1 and rng.random() < SIREN_CHARM_RATE:
        return "操舵室", "c", library_claimants[0]

    # 妨害する相手がいない日。操舵室に固定せず、乗客と同じくらい談話室にも行く。
    dest = "操舵室" if rng.random() < SIREN_BRIDGE_WEIGHT else "談話室"
    return dest, "c", None


