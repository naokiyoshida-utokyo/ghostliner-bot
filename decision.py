#   ので、1人ぶんの感情を書き込む場所が無い）。
#   代わりに、★出力の直前に足す下駄として扱う：
#       実効的な怪しさ = suspicion_score(worlds, 相手) + 敵対心
#   影響するのは「誰の名前を出すか」と「誰に投票するか」の2か所だけ。
#   証拠集合の絞り込みなど、論理として口に出す部分には一切かけない
#   （感情で絞ると、信念と矛盾したことを言い出してしまうため）。
GRUDGE_LIBRARY_ACCUSED = 0.30   # 図書室で「カロン陣営だ」と名指しされた
