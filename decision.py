#   「自分たちカロン陣営が全員抜けたら、操舵室に何人残りそうか」の見積もりで行う。
#
#   はじめはユーザーの案どおり単純な引き算（差が0〜2なら狙う）にしたが、
#   **人数によって意味が変わってしまい7人プレイが壊れた**。
#     ・9人プレイ：人間陣営6人・必要3人 → 差3。1人死ぬまで発動しない（意図どおり）
#     ・7人プレイ：人間陣営5人・必要3人 → 差2。**初日から毎日発動**
#   実測では7人プレイで人数不足が92%のゲームで起き、カロンが談話室に74%も
#   いる（本業の×を出さない）状態になった。
#   さらに差を3にすると9人プレイも同じ壊れ方をする（人数不足68%・人間勝率88%）。
#
#   見積もりなら人数構成が変わっても意味が保たれる：
#     ・9人の初日 → 航海士2×1.0 ＋ 乗客4×0.7 ＝ 4.8人（必要3人＋余裕1.5より多い→狙わない）
#     ・7人の初日 → 航海士2×1.0 ＋ 乗客3×0.7 ＝ 4.1人（同上→狙わない）
#     ・終盤で航海士1・乗客2 → 1.0＋1.4 ＝ 2.4人（必要3人に届かない→狙う）
#   ★ただし見積もりだけでは足りない。「7人プレイの初日（航海士2＋乗客3）」と
#     「9人プレイで1人死んだ後（航海士2＋乗客3）」は、どちらも見積もり4.1人で
