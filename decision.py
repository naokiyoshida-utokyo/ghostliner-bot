GRUDGE_NAMED_IN_TALK = 0.08     # 朝の議論で名指しで疑われた
GRUDGE_DECAY = 0.75             # 1日たつごとに薄れる割合（引きずりすぎない）
GRUDGE_MAX = 0.45
# ★上限がある理由：これを大きくすると、推理の結果を感情が完全に
#   上書きしてしまい、「証拠を無視して喧嘩しているだけのAI」になる。
#   0.45なら、確信度が大きく離れている相手を追い越すことはできない。


def new_grudges():
    """敵対心の記録を作る（{自分: {相手: 強さ}}）"""
    return {}


def decay_grudges(grudges):
    """1日ぶん、敵対心を薄れさせる（毎日1回だけ呼ぶ）"""
    for table in grudges.values():
        for other in list(table):
            table[other] *= GRUDGE_DECAY
            if table[other] < 0.02:
                del table[other]


def add_grudge(grudges, me, other, amount):
    """me が other に対して敵対心を持つ"""
    if not me or not other or me == other:
        return
    table = grudges.setdefault(me, {})
    table[other] = min(GRUDGE_MAX, table.get(other, 0.0) + amount)


def grudge_of(grudges, me):
    """me が今持っている敵対心の一覧（発言・投票に渡す下駄）"""
    return grudges.get(me, {}) if grudges else {}


