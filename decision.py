def passenger_plan_destination(worlds, players, my_name, rng=random,
                               alive_players=None, c_pt=0, win_c=None,
                               my_public_suspicion=0.0,
                               bridge_crowd_estimate=None, bridge_need=0,
                               shortage_yesterday=False):
    """
    図書室に行かないと決まった乗客が、操舵室と談話室のどちらへ行くかを決める。

    操舵室の方をやや優先するのは、ルールブック「乗客の基本」の
    「少なくとも1人は毎ターン操舵室に行き、疑似・航海士として振舞おう」
    という考え方を反映しています（比率(PASSENGER_BRIDGE_WEIGHT)は仮の値です）。

    そのうえで、次の2つの場合だけ確率を差し替えます。

      ①リーチの日（PASSENGER_BRIDGE_WEIGHT_REACH）
        今日みんなが操舵室で○を出せば○pt勝利に届く日。カロンは高確率で×を
        出して止めに来るので、★あえて操舵室の人数を減らし、「×を出したのは
        誰か」を絞り込みにいきます（上の定数の説明を参照。直感と逆ですが、
        自己対戦で確かめた結論です）。
        ただし前日の操舵室がぎりぎりの人数しかなかった日は、人数不足で
        ×ptを献上しないよう逆に多めに出ます
        （PASSENGER_BRIDGE_WEIGHT_REACH_SHORTHANDED）。

      ②前日の操舵室に余裕があった日（PASSENGER_BRIDGE_WEIGHT_RELAXED）
        「今日は誰か行くだろう」と気を抜きます。たまに全員が同時に気を抜いて
        人数不足の事故が起きる、という人間らしい揺れを作るための処理です。

      ③自分が強く疑われている日（PASSENGER_BRIDGE_WEIGHT_SUSPECTED）
        現在は無効（定数の説明を参照）。有効にすると操舵室に出て○を出し、
        働いている姿を見せるようになります。

      ④前日に人数不足が起きた日（PASSENGER_BRIDGE_WEIGHT_AFTER_SHORTAGE）
        「ちゃんと操舵室に来てくれよ」と慌てて集まります。②の揺り戻し。

    alive_players / c_pt / win_c : ①の判定に使う。省略すると①は働かない
      （＝今までどおりの固定確率のまま。既存の呼び出しを壊さないための保険）。
    bridge_crowd_estimate / bridge_need : ①の人数不足の歯止めに使う。
      前日の操舵室の人数（＝全員が見た公開情報）を渡すこと。
      ★「今日この人が操舵室に行くと決めた」という当日の情報を渡してはいけない。
        Discordでは当日の行先は結果発表まで伏せられているので、情報漏洩になる。
    my_public_suspicion : 「他人から見て」自分がどれくらい疑われているか(0.0〜1.0)。
      ★カロンの時と同じ注意が必要です。自分の信念状態から計算するのではなく、
        公開情報だけで組み立てた信念状態(public_worlds)から計算した値を
        外から渡してください。乗客は自分が乗客だと知っているので、自分視点だと
        必ず0%になってしまい、判定が永久に働きません。
    """
    weight = PASSENGER_BRIDGE_WEIGHT

    # ①リーチの日か（カロンが何人生きているかは知らないので期待値で見積もる）
    if win_c and alive_players:
        possible = expected_charon_free_count(worlds, alive_players)
        if humans_reach_point_win(c_pt, win_c, possible):
            shorthanded = (bridge_crowd_estimate is not None
                           and bridge_crowd_estimate <= bridge_need)
            weight = (PASSENGER_BRIDGE_WEIGHT_REACH_SHORTHANDED if shorthanded
                      else PASSENGER_BRIDGE_WEIGHT_REACH)

    # ②前日の操舵室に余裕があったら「今日は誰か行くだろう」と気を抜く。
    #   下げる方向なので min で合成する（リーチの日の方がさらに低ければ、
    #   そちらを優先したい）。
    if (bridge_crowd_estimate is not None
            and bridge_crowd_estimate >= bridge_need + PASSENGER_BRIDGE_CROWDED_MARGIN):
        weight = min(weight, PASSENGER_BRIDGE_WEIGHT_RELAXED)

    # ③自分が疑われているか（現在は同じ値なので実質なにも起きない）
    if my_public_suspicion >= PASSENGER_SUSPECTED_THRESHOLD:
        weight = max(weight, PASSENGER_BRIDGE_WEIGHT_SUSPECTED)

    # ④前日、人数不足で操舵が失敗していたら、今日は操舵室に出る
    #   （「ちゃんと操舵室に来てくれよ」の再現。他のどの事情より優先する）
    if shortage_yesterday:
        weight = max(weight, PASSENGER_BRIDGE_WEIGHT_AFTER_SHORTAGE)

    return "操舵室" if rng.random() < weight else "談話室"


