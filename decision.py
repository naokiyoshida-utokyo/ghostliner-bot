def decide_vote(worlds, players, my_name, alive_players, threshold=VOTE_SUSPICION_THRESHOLD,
                exclude=None, rng=random, grudge=None):
    """
    夜の投票で誰に入れるか（棄権するなら None）を決める。

    考え方：
      ・一番怪しい人（カロン＋セイレーンらしさが最大の人）を探す。
      ・ただし確信が薄いまま追放すると、人間陣営が自滅するだけなので
        （ルールブック「乗客の基本」：不確かな状況での安易な追放は避けよう）、
        怪しさが threshold を超えていなければ棄権する。
      ・一番怪しい人「だけ」を見るのではなく、そこから VOTE_SPREAD_MARGIN 以内に
        いる候補を集め、怪しさに応じた重み付き抽選で1人選ぶ。
        ★これが無いと、同じ公開情報を見ているAI全員の票が必ず一致してしまう
          （talk.py が名指しの相手を選ぶ時と同じ理由・同じ仕組み。
            VOTE_SPREAD_MARGIN の説明を参照）。

    exclude：最初から投票先の候補にしたくない人の集合。
      ★これが必要な理由：カロン同士は互いの正体を100%知っているので、
        何も対策しないと「一番怪しい人」を探した結果、自分の仲間の
        カロンが100%の怪しさで見つかってしまい、誤って仲間に投票して
        しまいます（実際にシミュレーターで発生を確認した不具合です）。
        なので、呼び出す側（カロンなら自分の仲間）が exclude で
        あらかじめ除外してください。

    grudge：この人が今持っている敵対心 {相手: 強さ}（GRUDGE_* のコメント参照）。
      ★推理そのものではなく、票を決める直前に足す下駄。
        「図書室で自分をカロンだと名指しした相手」「昨夜自分に入れてきた相手」に
        票を入れ返す、という人間くさい動きを作るためのもの。
    """
    exclude = exclude or set()
    candidates = [p for p in alive_players if p != my_name and p not in exclude]
    if not candidates:
        return None

    grudge = grudge or {}
    scored = sorted(((p, min(1.0, suspicion_score(worlds, p) + grudge.get(p, 0.0)))
                     for p in candidates),
                    key=lambda x: x[1], reverse=True)

    # 一番怪しい人ですら閾値に届かないなら、誰にも入れない（棄権）
    top_score = scored[0][1]
    if top_score < threshold:
        return None

    # 一番怪しい人からVOTE_SPREAD_MARGIN以内で、かつ閾値も超えている人だけを候補に。
    # 「閾値も超えている」を条件に入れているのは、揺らぎのせいで
    # 「自分では投票する気にならないくらい白い人」に票が流れないようにするため。
    cluster = [(p, s) for p, s in scored
               if s >= top_score - VOTE_SPREAD_MARGIN and s >= threshold]
    weights = [s for _, s in cluster]
    if sum(weights) <= 0:
        return rng.choice([p for p, _ in cluster])
    return rng.choices([p for p, _ in cluster], weights=weights, k=1)[0]


