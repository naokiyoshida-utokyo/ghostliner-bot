# ---- 操舵室の「人数不足」を狙う（カロン陣営） ----
# 操舵室に bridge_need 人集まらないと操舵は自動的に失敗し、×ptが1入る。
# ★なぜわざわざ作るのか（ユーザーの実プレイ経験）
#   人間同士のプレイでは、カロンに殺されたり誤って人間陣営を追放したりして
