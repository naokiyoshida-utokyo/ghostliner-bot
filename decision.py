def humans_reach_point_win(c_pt, win_c, possible_c_cards):
    """
    人間陣営が「今日のうちに○ptでの勝利に届いてしまう」状態か（＝リーチ）。

    possible_c_cards: 今日出うる○の最大枚数。カロン以外は操舵室で必ず○を
                      出すので、「生きているカロン以外の人数」がそのまま
                      最大枚数になる（全員が操舵室に行った場合）。

    ★カロンとセイレーンの両方から使う共通の判定にしてある。
      図書室に立候補するかどうかの判断にも使うので、
      同じ式を2か所に書かないようにここへ置いた。
    """
    return c_pt + possible_c_cards >= win_c


def charon_plan_action(
    worlds, players, my_name, ally_name, alive_players, day, x_pt, win_x,
    played_x_yesterday=False, ally_played_x_yesterday=False,
    c_pt=0, win_c=99, my_public_suspicion=0.0,
    bridge_crowd_so_far=0, bridge_need=0, deaths_count=0, rng=random,
):
    """
    カロンが「行先・カード・攻撃対象」をどうするかを決める。

    戻り値: (行先, カード, 攻撃対象 or None)

    考え方（ルールブック「カロンの基本」＋実プレイで見られる立ち回りを反映）：
      0. 人数勝利（生存者の半数以上をカロンで占める）への王手。
         ここだけは確率ではなく確定ルールです。勝利条件の式
         「カロンの生存人数×2 ≧ 生存者総数」を基準に、
         あとN人殺せば人数勝利に届く、という局面で使う。
           ・N=2（カロンが2人生存中に限る）：航海士を2人とも100%
             特定できているなら、2人のカロンがそれぞれ別の航海士を
             担当して同時に談話室へ行き、狙う。
           ・N=1：航海士を1人でも100%特定できているなら、必ず殺しにいく
             （カロンが1人でも2人でも実行する。2人生存中は重複を避け、
              先番(my_rank=0)側だけが実行する）。
         これはクールダウンや「攻撃は最後の手段」より優先する
         （見逃したら勝ちを逃す、決定的な場面のため）。
      1. 終盤の勝負手：カロンが2人とも生きていて、×ptが勝利まであと
         ENDGAME_X_MARGIN以内に迫っているなら、強引に操舵室へ行き×を出して
         押し切りにいく（1人しか追放できない夜の仕組み上、2人生存していれば
         最低1人は生き残るため、これが勝ち筋になる）。
      1.5 人間陣営のリーチ潰し：今日、生きている人間陣営が全員操舵室で○を
         出したら○pt勝利に届いてしまう日は、CHARON_BLOCK_REACH_RATEの
         高確率で操舵室へ行き×を出す。×が1枚出れば○は全部無効になるので、
         止めるだけなら1人で足りる。担当（名前順で先番）が出し、相方は
         CHARON_BLOCK_REACH_BACKUP_RATEの確率で保険として加わる（担当が
         亡霊に談話室へ落とされた日の取りこぼし対策）。加わらない日の相方は
         談話室へ行く（操舵室で○を出すと、止め損ねたときに自分の○が
         人間陣営の勝ちを後押ししてしまうため）。
         クールダウン（手順2）より優先する＝もう後がないため。
      2. クールダウン：前日に自分が×を出していたら、その日は談話室へ行き、
         何もしない（攻撃もしない）。×を出した直後は一番疑われやすいので、
         あえて目立つ行動を避けて疑いが薄れるのを待つ。
      3. 攻撃は「最後の手段」。航海士らしき人が見えていても、普段は攻撃
         しない。攻撃すると「談話室に攻撃者がいた」という強い手がかりを
         残してしまい、自分の身が危うくなるからです。カロン陣営は人数が
         少なく、自分の命と人間1人の命が釣り合わないため、割に合いません。
         次のどちらかに当てはまるときだけ、攻撃を検討します：
           ・人間陣営の○ptが勝利目前（ATTACK_ONLY_IF_C_PT_MARGIN以内）に
             迫っていて、このままでは負ける
           ・自分がすでに強く疑われていて（ATTACK_IF_ALREADY_SUSPECTED以上）、
             どうせ次に追放されるので失うものがない
      4. それ以外は「初日から」積極的に×ptを稼ぎに行く。
         仲間のカロンと2人そろって操舵室に行くと、〇✕の内訳からカロンが
         2人いることまでバレる危険があるため（ルールブック：「カロンが
         2人とも操舵室に行くのは避けるべきだ」）、2人のうちどちらが
         操舵室に行くかを分担する（実プレイでの「今日は俺は操舵室に
         行こうかな」という、さりげない意思疎通に相当）。
         仲間が前日×を出してクールダウン中（＝手順2で談話室にいる）なら、
         自分が操舵室を引き受ける。どちらもクールダウン中でなければ、
         日替わりで担当を決める。
         操舵室の担当になった方は、朝の議論で航海士・乗客が先に行先を
         決めた「実際の集まり具合」を見て、必要人数よりCHARON_X_SAFE_CROWD_MARGIN
         人以上多く既に集まっていれば「混んでいる」とみなしCHARON_X_PROBABILITY_CROWDEDの
         高確率で×を出し、そうでなければCHARON_X_PROBABILITY_THINまで控えめにする
         （ルールブック：「大勢の中なら紛れ込みやすいが、少人数で×を出すと
           早々にバレる」の実装。朝の議論で航海士・乗客→カロン→セイレーンの
           順に行先を決めるようにしているので、実際の人数を見てから判断できる）。
         談話室担当は攻撃の機会をうかがう（このターンは何もしない）。

    played_x_yesterday     : 自分が前日に×を出していたか
    ally_played_x_yesterday: 仲間が前日に×を出していたか（＝今日クールダウン中か）
    c_pt, win_c            : 人間陣営の現在の○ptと、勝利に必要な○pt
                             （攻撃するかどうかの判断に使う）
    my_public_suspicion    : 「他人から見て」自分がどれくらい疑われているか(0.0〜1.0)。
                             ★自分の信念状態(worlds)から計算してはいけません。
                               カロンは自分がカロンだと知っているので、そこから
                               計算すると必ず100%になってしまいます。公開情報だけで
                               組み立てた信念状態から計算した値を、外から渡してください。
    bridge_crowd_so_far    : 朝の議論で、自分より先に「操舵室に行く」と
                             決めた人の人数（航海士・乗客の実際の行先を集計した値）
    bridge_need            : 操舵室の成立に必要な人数（人数不足の判定に使う値）
    """
    # ally_name は「仲間がもう生きていない（誰もいない）」場合に None が
    # 渡ってくる想定。None は誰の名前とも一致しないので、その場合は
    # 必ず ally_alive=False として扱う。
    ally_alive = ally_name is not None and ally_name in alive_players
    attackable = [p for p in alive_players if p not in (my_name, ally_name)]
    # 仲間内での自分の順番（0か1）。名前のアルファベット順で決めるだけなので、
    # 仲間側が同じ計算をすれば、示し合わせなくても自然に役割が分かれる。
    i_am_first = (not ally_alive) or (my_name < ally_name)
    my_rank = 0 if i_am_first else 1

    # 0. 人数勝利への王手（確定ルール。他の何よりも優先する）
    charon_alive_count = 2 if ally_alive else 1
    headcount_margin = len(alive_players) - 2 * charon_alive_count
    navigator_locks = sorted(
        p for p in attackable if engine.role_ratio(worlds, p, "航海士") >= HEADCOUNT_ID_CONFIDENCE
    )

    if headcount_margin == 2 and ally_alive and len(navigator_locks) >= 2:
        return "談話室", "c", navigator_locks[my_rank % len(navigator_locks)]

    if headcount_margin == 1 and navigator_locks:
        if not ally_alive or my_rank == 0:
            return "談話室", "c", navigator_locks[0]

    # 1. 終盤の勝負手（2人そろって×で押し切る。リーチ潰しより優先＝こちらは
    #    「止める」ではなく「勝ちにいく」手なので、2人とも×を出す）
    if ally_alive and x_pt >= win_x - ENDGAME_X_MARGIN:
        return "操舵室", "x", None

    # 1.2 人数不足を狙う日か（操舵室に行かないことが目的なので、以降の
    #     「操舵室へ行く」判断をすべて抑える）。
    #     ★リーチ潰し(1.5)より優先してよい理由：操舵室が人数不足で不成立に
    #       なれば○は1枚も入らないので、リーチも自動的に止まる。しかも
    #       「×を出した人」として疑われるリスクがない、上位互換の手になる。
    seek_shortage = charon_side_seeks_shortage(
        worlds, alive_players, bridge_need, deaths_count=deaths_count, rng=rng)

    # 今日どちらが操舵室を引き受けるかの分担。手順1.5と手順4で共通に使う。
    # ★毎回同じ人が×を出すと、その1人に疑いが集中して即バレするので、
    #   日替わりで交代する（仲間がクールダウン中の日は自分が引き受ける）。
    if ally_alive and not ally_played_x_yesterday:
        i_go_bridge = (i_am_first == (day % 2 == 0))
    else:
        i_go_bridge = True

    # 1.5 人間陣営のリーチを止める（クールダウンより優先。もう後がない）
    #     ×が1枚でも出れば○は全部無効になるので、止めるだけなら1人で足りる。
    #     担当が高確率で出し、相方は保険で加わる。
    if not seek_shortage and humans_reach_point_win(c_pt, win_c, len(attackable)):
        if i_go_bridge:
            card = "x" if rng.random() < CHARON_BLOCK_REACH_RATE else "c"
            return "操舵室", card, None
        if rng.random() < CHARON_BLOCK_REACH_BACKUP_RATE:
            return "操舵室", "x", None
        # 保険に加わらない日は談話室へ。操舵室で○を出すと、担当が止め損ねた
        # ときに自分の○が人間陣営の勝ちを後押ししてしまう。
        return "談話室", "c", None

    # 2. クールダウン：前日×を出していたら、今日は大人しくする
    if played_x_yesterday:
        return "談話室", "c", None

    # 3. 攻撃は最後の手段。追い込まれているときだけ検討する
    humans_are_close_to_winning = c_pt >= win_c - ATTACK_ONLY_IF_C_PT_MARGIN
    i_am_already_suspected = my_public_suspicion >= ATTACK_IF_ALREADY_SUSPECTED
    if day >= ATTACK_START_DAY and (humans_are_close_to_winning or i_am_already_suspected):
        target = choose_attack_target_for_charon(worlds, attackable, my_rank)
        if target is not None:
            return "談話室", "c", target  # 談話室ではカードは使われないのでダミーで○

    # 4. 初日からの×ptプレッシャー。仲間と操舵室担当を分ける
    #    （分担は上で計算済みの i_go_bridge を使う）
    if ally_alive:
        if i_go_bridge and not seek_shortage:
            is_crowded = bridge_crowd_so_far >= bridge_need + CHARON_X_SAFE_CROWD_MARGIN
            x_prob = CHARON_X_PROBABILITY_CROWDED if is_crowded else CHARON_X_PROBABILITY_THIN
            card = "x" if rng.random() < x_prob else "c"
            return "操舵室", card, None
        return "談話室", "c", None

    # 仲間がもういない場合は、目立たないよう○でブレンドするだけにする
    # （人数不足を狙う日はそれも我慢して談話室へ）
    if seek_shortage:
        return "談話室", "c", None
    return "操舵室", "c", None


