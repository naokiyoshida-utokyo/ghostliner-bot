# 図書室の立候補フェーズ（朝の議論）
# ============================================================
#
# 実際の卓と同じように、2段階で決めます。
#
#   第1段階：「図書室に行きたい人？」と聞かれて、手を挙げるかどうか
#   第2段階：手を挙げた人が出そろってから、本当に行くか、譲って引くか
#
# こうすることで、複数人が図書室に突っ込んでカードを無駄にする事故
# （ルールブック：複数人が行くと誰も確認できない）を、実際の卓と同じように
# 話し合いで避けられます。
#
# ★将来Discordに組み込むときは、この2段階がそのままチャットの
#   やり取りになります（「図書室に行きたい人は挙手してください」→
#   「立候補は3人です。取り下げる人はいますか？」）。
#   人間プレイヤーはボタンで答え、AIはここの確率で答える、という形です。


def game_urgency(c_pt, win_c, x_pt, win_x):
    """
    「決着がどれくらい近いか」を 0.0〜1.0 で返す。

    ○ptと×ptのうち、勝利ラインに近い方の進み具合をそのまま使います
    （どちらの陣営が勝つにせよ、ゲームが終われば図書室カードは無駄になるため）。

    ★どちらも全員に公開されている情報なので、これを判断材料に使っても
      情報漏洩にはなりません。
    """
    if not win_c or not win_x:
        return 0.0
    return max(min(c_pt / win_c, 1.0), min(x_pt / win_x, 1.0))


def expected_charon_free_count(worlds, alive_players):
    """
    生存者のうち「カロンではない人」の期待人数を、自分の信念状態から見積もる。

    ★何に使うか
      人間陣営がリーチかどうか（humans_reach_point_win）を、乗客自身にも
      判定させるために使います。カロン本人は仲間が誰か知っているので
      「生存者数 − 2」と正確に数えられますが、乗客は誰がカロンかを知りません。
      そこで、自分が持っている「その人がカロンである確率」を全員ぶん足し合わせて
      期待値として使います。

    ★セイレーンを引かないのが正しい理由
      セイレーンは操舵室で必ず○を出すので、○の枚数としては人間陣営と同じく
      1枚ぶん数えられます。カロン側の judgement（len(attackable)）も
      「生存者 − カロン2人」でセイレーンを含めているので、それと揃えています。

    ★情報漏洩にはなりません
      ここで使っているのは自分の信念状態だけで、結果として起きる行動も
      「操舵室に行く」だけです。誰かを名指ししたり、知らないはずの事実を
      口にしたりはしないので、他人から見て不自然にはなりません。
    """
    return sum(1.0 - engine.role_ratio(worlds, p, "カロン") for p in alive_players)


def expected_bridge_without_charon_side(worlds, alive_players):
    """
    「カロン陣営が全員操舵室に行かなかったら、操舵室に何人集まりそうか」を
    自分の信念状態から見積もる。

    航海士はルールで必ず操舵室に行くので1人ぶんそのまま、乗客は普段の確率
    （PASSENGER_BRIDGE_WEIGHT）ぶんだけ数える。

    ★なぜ「人間陣営の人数」ではなくこの見積もりを使うのか
      単純な人数の引き算だと、プレイ人数によって意味が変わってしまうため
      （定数 CHARON_SHORTAGE_SLACK の説明を参照。7人プレイが壊れた）。
      「操舵室が成立しそうか」を直接見積もれば、人数構成が変わっても
      同じ意味を保てる。

    ★なぜ期待値で見積もるのか
      カロンはセイレーンの正体を知らない（セイレーンが一方的にカロンを知る仕様）。
      誰が人間陣営かを正確には数えられないので、自分の信念状態から
      「その人が航海士である確率」「乗客である確率」を使って足し合わせる。
      セイレーンから呼ぶ場合はカロンの正体を知っているぶん、より正確になる。
    """
    return sum(
        engine.role_ratio(worlds, p, "航海士")
        + engine.role_ratio(worlds, p, "乗客") * PASSENGER_BRIDGE_WEIGHT
        for p in alive_players
    )


def charon_side_seeks_shortage(worlds, alive_players, bridge_need,
                               deaths_count=0, rng=random):
    """
    今日は操舵室を避けて「人数不足による操舵失敗」を狙う日か。

    カロン・セイレーンの両方から呼ぶ（どちらも操舵室に行かないことが必要なため）。
    ★示し合わせずに各自が独立に確率を振る。全員が同時に必ず避けると
      「必要人数ぎりぎりの日は必ず操舵室がガラガラになる」という機械的な型が
      できてしまい、人間から読まれる。取りこぼす日があってよい。

    deaths_count: これまでの脱落者の人数（追放・攻撃を問わない。公開情報）。
      まだ誰も欠けていないうちは狙わない（定数の説明を参照）。
    """
    if not alive_players or deaths_count < CHARON_SHORTAGE_MIN_DEATHS:
        return False
    expected = expected_bridge_without_charon_side(worlds, alive_players)
    if expected > bridge_need + CHARON_SHORTAGE_SLACK:
        return False
    return rng.random() < CHARON_SEEK_SHORTAGE_RATE


